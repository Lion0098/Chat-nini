type Prefs = {
  locale: Locale;
  theme: "light" | "dark";
  setLocale: (locale: Locale) => void;
  setTheme: (theme: "light" | "dark") => void;
  t: (key: CopyKey) => string;
  err: (code: string) => string;
};

const Ctx = createContext<Prefs | null>(null);

export function PrefsProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fa");
  const [theme, setThemeState] = useState<"light" | "dark">("light");

  useEffect(() => {
    const saved = localStorage.getItem("nini-locale");
    if (saved === "en" || saved === "fa") setLocaleState(saved);
    const th = localStorage.getItem("nini-theme");
    if (th === "dark" || th === "light") setThemeState(th);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "fa" ? "fa" : "en";
    document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";
    document.documentElement.classList.toggle("dark", theme === "dark");
    localStorage.setItem("nini-locale", locale);
    localStorage.setItem("nini-theme", theme);
  }, [locale, theme]);

  const value = useMemo<Prefs>(() => {
    const table = locale === "en" ? en : fa;
    return {
      locale,
      theme,
      setLocale: setLocaleState,
      setTheme: setThemeState,
      t: (key) => table[key],
      err: (code) => table[ERROR_KEY[code] ?? "errGeneric"],
    };
  }, [locale, theme]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function usePrefs() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("prefs");
  return ctx;
}
